"""Rasterize Pixelify Sans (SIL OFL 1.1) into src/m3_launcher_font.h.

The launcher draws its text with the ROM's own font; the untranslated Japanese
ROM has no Latin letters there, so it uses this table instead. Glyphs match the
ROM font's cell: 16x16, capitals on rows 0-7, descenders below.
Usage: python tools/make_launcher_font.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "android/app/src/main/res/font/pixelify_sans.ttf"
OUT = ROOT / "src/m3_launcher_font.h"

font = ImageFont.truetype(str(FONT), 12)  # 12 px: crisp, 8 px capitals like the ROM font
rows = []
for code in range(32, 127):
    im = Image.new("1", (32, 32), 0)
    draw = ImageDraw.Draw(im)
    draw.fontmode = "1"
    draw.text((4, 0), chr(code), font=font, fill=1)
    px = im.load()
    cols = [x for x in range(32) if any(px[x, y] for y in range(32))]
    left = cols[0] if cols else 0
    bits = []
    for y in range(16):
        v = 0
        for x in range(16):
            # PIL puts the capital line 4 px down at this size.
            if left + x < 32 and y + 4 < 32 and px[left + x, y + 4]:
                v |= 0x8000 >> x
        bits.append(v)
    rows.append(bits)

lines = [
    "// Generated by tools/make_launcher_font.py from Pixelify Sans",
    "// (c) 2021 The Pixelify Sans Project Authors, SIL Open Font License 1.1.",
    "// Printable ASCII from space; each glyph is 16 rows, bit 15 = leftmost pixel.",
    "#pragma once",
    "#include <cstdint>",
    "",
    "static constexpr std::uint16_t kLauncherFont[95][16] = {",
]
for code, bits in zip(range(32, 127), rows):
    shown = chr(code).replace("\\", "backslash")
    lines.append("    {" + ", ".join(f"0x{v:04X}" for v in bits) + "},  // " + shown)
lines.append("};")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT}")
